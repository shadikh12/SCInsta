#!/usr/bin/env python3
"""
Generates src/FeatureCheckTable.h: for every boolean setting, the Instagram
classes/methods its hooks depend on. FeatureCheck.m uses it at runtime to
report enabled features that won't work on the installed Instagram version.

Run from the repo root: python3 scripts/gen_feature_check.py
(the Makefile runs it automatically before each build)
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src')
OUT = os.path.join(SRC, 'FeatureCheckTable.h')

PREF_RE = re.compile(r'getBoolPref:\s*@"(\w+)"')
HOOK_RE = re.compile(r'^\s*%hook\s+(\S+)', re.M)
METHOD_RE = re.compile(r'^\s*([-+])\s*\([^)]*\)\s*([^{;]+?)\s*\{', re.M)
DEFINE_RE = re.compile(r'^\s*#define\s+(\w+)(?:\([^)]*\))?((?:.*\\\n)*.*)$', re.M)
STATIC_FN_RE = re.compile(r'^static\s+[\w\s\*]+?\b(\w+)\s*\([^)]*\)\s*\{', re.M)


def match_brace(text, open_idx):
    depth = 0
    for i in range(open_idx, len(text)):
        if text[i] == '{':
            depth += 1
        elif text[i] == '}':
            depth -= 1
            if depth == 0:
                return i
    return len(text) - 1


def selector(sig):
    if ':' not in sig:
        return sig.split()[0]
    sig = re.sub(r'\([^)]*\)', ' ', sig)
    return ''.join(p + ':' for p in re.findall(r'(\w+)\s*:', sig))


def prefs_in(body, callables):
    prefs = set(PREF_RE.findall(body))
    for name, p in callables.items():
        if re.search(r'\b' + name + r'\b', body):
            prefs |= p
    return prefs


def setting_titles():
    path = os.path.join(SRC, 'Settings', 'TweakSettings.m')
    text = open(path, encoding='utf-8').read()
    return dict((k, t) for t, k in re.findall(
        r'switchCellWithTitle:@"((?:[^"\\]|\\.)*)"\s*subtitle:@"(?:[^"\\]|\\.)*"\s*defaultsKey:@"(\w+)"', text))


def hook_entries():
    entries = []
    for root, _, files in os.walk(os.path.join(SRC, 'Features')):
        files += []
        for fn in sorted(files):
            if fn.endswith(('.x', '.xm')):
                entries += file_entries(os.path.join(root, fn))
    entries += file_entries(os.path.join(SRC, 'Tweak.x'))
    return entries


def file_entries(path):
    text = open(path, encoding='utf-8').read()

    # Macros & static helper functions that check prefs (resolved transitively)
    callables = {}
    for m in DEFINE_RE.finditer(text):
        callables[m.group(1)] = m.group(2)
    for m in STATIC_FN_RE.finditer(text):
        brace = text.index('{', m.end() - 1)
        callables[m.group(1)] = text[brace:match_brace(text, brace) + 1]
    resolved = {k: set(PREF_RE.findall(v)) for k, v in callables.items()}
    for _ in range(3):
        for k, v in callables.items():
            resolved[k] |= prefs_in(v, {n: p for n, p in resolved.items() if n != k})

    entries = []
    for hm in HOOK_RE.finditer(text):
        cls = hm.group(1)
        end = text.find('%end', hm.end())
        block = text[hm.end():end]
        for mm in METHOD_RE.finditer(block):
            if '%new' in block[max(0, mm.start() - 20):mm.start() + 6]:
                continue
            brace = mm.end() - 1
            body = block[brace:match_brace(block, brace) + 1]
            for pref in sorted(prefs_in(body, resolved)):
                entries.append((pref, cls, selector(mm.group(2)), mm.group(1) == '+'))
    return entries


def main():
    titles = setting_titles()
    seen, rows = set(), []
    for e in hook_entries():
        if e[0] in titles and e not in seen:
            seen.add(e)
            rows.append(e)
    rows.sort(key=lambda r: (r[0], r[1], r[2]))

    def c(s):
        return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

    lines = [
        '// Generated by scripts/gen_feature_check.py -- do not edit by hand',
        '',
        'typedef struct {',
        '    const char *pref;',
        '    const char *title;',
        '    const char *cls;',
        '    const char *sel;',
        '    BOOL isClassMethod;',
        '} SCIFeatureHook;',
        '',
        'static const SCIFeatureHook SCIFeatureHooks[] = {',
    ]
    for pref, cls, sel, is_cls in rows:
        lines.append(f'    {{ {c(pref)}, {c(titles[pref])}, {c(cls)}, {c(sel)}, {"YES" if is_cls else "NO"} }},')
    lines += ['};', '']
    content = '\n'.join(lines)

    old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else None
    if content != old:
        open(OUT, 'w', encoding='utf-8', newline='\n').write(content)
    print(f'{len(rows)} hooks across {len({r[0] for r in rows})} features -> {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    main()
